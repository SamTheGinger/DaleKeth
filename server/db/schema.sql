-- Application tables, applied by `npm run db:migrate`. Idempotent (IF NOT EXISTS throughout).
-- Better Auth owns "user", "session", "account" and "verification"; tables below reference "user"(id).
-- Monetary columns are whole rand.

-- ---------------------------------------------------------------------------
-- Catalogue (populated by `npm run db:seed`)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS photos (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      text NOT NULL,
  category   text NOT NULL CHECK (category IN ('Portrait', 'Landscape')),
  src        text NOT NULL -- Cover image URL; image files are served by the frontend.
);

CREATE TABLE IF NOT EXISTS photo_images (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  photo_id   integer NOT NULL REFERENCES photos (id) ON DELETE CASCADE,
  position   integer NOT NULL,
  src        text NOT NULL,
  UNIQUE (photo_id, position)
);

CREATE TABLE IF NOT EXISTS artworks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  medium      text NOT NULL,
  size        text NOT NULL,
  price       integer NOT NULL CHECK (price >= 0),
  available   integer NOT NULL CHECK (available >= 0),
  src         text NOT NULL,
  description text NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  date        date NOT NULL,
  time        text NOT NULL,
  venue       text NOT NULL,
  price       integer NOT NULL CHECK (price >= 0), -- 0 = free event (reserved, not purchased).
  spots       integer NOT NULL CHECK (spots >= 0),
  src         text NOT NULL,
  description text NOT NULL
);

-- ---------------------------------------------------------------------------
-- User activity
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS favorites (
  user_id    text NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
  photo_id   integer NOT NULL REFERENCES photos (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, photo_id)
);

-- Form submissions. user_id is set when the visitor was signed in.
CREATE TABLE IF NOT EXISTS purchase_requests (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artwork_id integer NOT NULL REFERENCES artworks (id),
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  quantity   integer NOT NULL CHECK (quantity > 0),
  name       text NOT NULL,
  email      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Reservations for free events. Paid events use orders below.
CREATE TABLE IF NOT EXISTS event_bookings (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id   integer NOT NULL REFERENCES events (id),
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  spots      integer NOT NULL CHECK (spots > 0),
  name       text NOT NULL,
  email      text NOT NULL,
  phone      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS photoshoot_bookings (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  name       text NOT NULL,
  email      text NOT NULL,
  phone      text NOT NULL,
  style      text NOT NULL CHECK (style IN ('landscape', 'portrait')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Payments (Stripe Checkout)
-- ---------------------------------------------------------------------------

-- Created 'pending' by POST /api/checkout. Only the Stripe webhook may set 'paid'.
CREATE TABLE IF NOT EXISTS orders (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           text NOT NULL REFERENCES "user" (id), -- No cascade: accounts with orders can't be deleted.
  status            text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'expired')),
  total             integer NOT NULL CHECK (total >= 0),
  currency          text NOT NULL DEFAULT 'zar',
  stripe_session_id text UNIQUE,
  created_at        timestamptz NOT NULL DEFAULT now(),
  paid_at           timestamptz
);

-- Title and unit price are snapshotted at purchase time so later catalogue edits don't rewrite history.
CREATE TABLE IF NOT EXISTS order_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  event_id    integer NOT NULL REFERENCES events (id),
  title       text NOT NULL,
  unit_price  integer NOT NULL CHECK (unit_price >= 0),
  quantity    integer NOT NULL CHECK (quantity > 0)
);
