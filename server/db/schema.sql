-- The site's own tables. Run by `npm run db:migrate` (db/migrate.js).
-- The user, session, account and verification tables are NOT here: Better Auth creates
-- and owns those (migrate.js asks it to). Our tables point at its "user" table by id.
--
-- Every statement uses IF NOT EXISTS, so running this file again is safe: it only adds what's missing.

-- ---------------------------------------------------------------------
-- Content (filled by `npm run db:seed`)
-- ---------------------------------------------------------------------

-- One row per portfolio series (Copper, Ebony, Serenity, ...).
CREATE TABLE IF NOT EXISTS photos (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      text NOT NULL,
  category   text NOT NULL CHECK (category IN ('Portrait', 'Landscape')),
  src        text NOT NULL -- The cover image path, e.g. /Images/Copper/C1.webp (the files live on the frontend).
);

-- The images inside each series, in order. A separate table because one photo has many images.
CREATE TABLE IF NOT EXISTS photo_images (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  photo_id   integer NOT NULL REFERENCES photos (id) ON DELETE CASCADE,
  position   integer NOT NULL, -- 0, 1, 2, ... keeps the gallery in the right order.
  src        text NOT NULL,
  UNIQUE (photo_id, position)
);

CREATE TABLE IF NOT EXISTS artworks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  medium      text NOT NULL,
  size        text NOT NULL,
  price       integer NOT NULL CHECK (price >= 0),     -- Rand, whole numbers.
  available   integer NOT NULL CHECK (available >= 0), -- Pieces left.
  src         text NOT NULL,
  description text NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  date        date NOT NULL,
  time        text NOT NULL,
  venue       text NOT NULL,
  price       integer NOT NULL CHECK (price >= 0),
  spots       integer NOT NULL CHECK (spots >= 0), -- The CHECK means a booking can never push this below zero.
  src         text NOT NULL,
  description text NOT NULL
);

-- ---------------------------------------------------------------------
-- Things visitors create
-- ---------------------------------------------------------------------

-- A signed-in user's favourite portfolio series. The pair (user, photo) can only appear once.
CREATE TABLE IF NOT EXISTS favorites (
  user_id    text NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
  photo_id   integer NOT NULL REFERENCES photos (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, photo_id)
);

-- The three forms on the site. user_id is filled in when the visitor was signed in, otherwise left empty.
CREATE TABLE IF NOT EXISTS purchase_requests (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artwork_id integer NOT NULL REFERENCES artworks (id),
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  quantity   integer NOT NULL CHECK (quantity > 0),
  name       text NOT NULL,
  email      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS event_bookings (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id   integer NOT NULL REFERENCES events (id),
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  spots      integer NOT NULL CHECK (spots > 0),
  name       text NOT NULL,
  email      text NOT NULL,
  phone      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS photoshoot_bookings (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    text REFERENCES "user" (id) ON DELETE SET NULL,
  name       text NOT NULL,
  email      text NOT NULL,
  phone      text NOT NULL,
  style      text NOT NULL CHECK (style IN ('landscape', 'portrait')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Payments (Stripe Checkout)
-- ---------------------------------------------------------------------

-- One row per purchase of event spots. Created as 'pending' when the buyer clicks Buy Now (routes/orders.js).
-- ONLY Stripe's webhook (routes/stripeWebhook.js) may change it to 'paid', once Stripe confirms the money arrived.
-- An order is always tied to a real account: checkout needs someone signed in, so user_id is NOT NULL.
CREATE TABLE IF NOT EXISTS orders (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           text NOT NULL REFERENCES "user" (id), -- No ON DELETE: an account with orders can't be deleted by accident.
  status            text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'expired')),
  total             integer NOT NULL CHECK (total >= 0),  -- Rand, whole numbers, worked out on the server from the prices below.
  currency          text NOT NULL DEFAULT 'zar',
  stripe_session_id text UNIQUE,                          -- The Stripe Checkout Session (cs_test_...) paying for this order.
  created_at        timestamptz NOT NULL DEFAULT now(),
  paid_at           timestamptz                           -- Filled in by the webhook.
);

-- What was bought in each order: spots for an event, and at what price. The title and price are COPIED here when
-- the order is made, so if an event's price changes later, old orders still show what the buyer actually paid.
CREATE TABLE IF NOT EXISTS order_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  event_id    integer NOT NULL REFERENCES events (id),
  title       text NOT NULL,
  unit_price  integer NOT NULL CHECK (unit_price >= 0), -- Rand, for ONE spot.
  quantity    integer NOT NULL CHECK (quantity > 0)     -- How many spots.
);
